async (page) => {
 await page.goto('http://127.0.0.1:5173/');
 await page.setViewportSize({width:1440,height:960});
 await page.evaluate(()=>window.__product.showAct('interruption'));
 await page.getByRole('button',{name:'查看未列入报表的部分',exact:false}).click();
 await page.getByRole('tab',{name:'鲜活之心'}).click();
 await page.waitForFunction(()=>window.__heartLab?.state.exposure<.005);
 const results=[];
 const check=(ok,name)=>{if(!ok)throw new Error(name);results.push(name);};
 await page.waitForFunction(()=>window.__heartLab?.ready);
 check(await page.locator('#bpm').textContent()==='72','healthy baseline');
 await page.getByRole('tab',{name:'烟草侵入'}).click();
 await page.getByRole('slider').focus();await page.keyboard.press('End');
 await page.waitForFunction(()=>window.__heartLab.state.exposure>.98);
 check(await page.locator('#flow-label').textContent()==='供血受限','high exposure slows flow');
 check(Number(await page.locator('#bpm').textContent())>=107,'high exposure accelerates heartbeat');
 const damage=await page.evaluate(()=>window.__heartLab.damage);
 check(damage.level>.98 && damage.visibleScars===30 && damage.plaqueOpacity>.99,'30 years produces structural lesions and visible plaques');
 await page.screenshot({path:'output/playwright/exposure-final.png'});
 await page.getByRole('button',{name:'探索冠状动脉',exact:true}).click();
 check(await page.locator('#info-dialog').isVisible(),'coronary annotation opens');
 check((await page.locator('.artery').getAttribute('style')).includes('17px'),'plaque cross section responds to exposure');
 await page.getByRole('button',{name:'关闭',exact:true}).click();
 await page.getByRole('tab',{name:'重获新生'}).click();
 await page.getByRole('slider').focus();await page.keyboard.press('End');
 await page.waitForFunction(()=>window.__heartLab.state.exposure<.17);
 check(Number(await page.locator('#bpm').textContent())<80,'recovery improves simulated rhythm');
 check((await page.evaluate(()=>window.__heartLab.damage.visibleScars))===0,'recovery reduces structural damage visualization');
 await page.screenshot({path:'output/playwright/recovery-final.png'});
 await page.getByRole('tab',{name:'鲜活之心'}).click();
 await page.waitForFunction(()=>window.__heartLab.state.exposure<.01);
 await page.getByRole('button',{name:'切换自动旋转',exact:true}).click();
 check(await page.getByRole('button',{name:'切换自动旋转',exact:true}).getAttribute('aria-pressed')==='true','auto rotation toggles');
 await page.getByRole('button',{name:'重置视角',exact:true}).click();
 const before=await page.evaluate(()=>window.__heartLab.camera.position.toArray());
 await page.mouse.move(1020,440);await page.mouse.down();await page.mouse.move(1110,470,{steps:12});await page.mouse.up();
 const after=await page.evaluate(()=>window.__heartLab.camera.position.toArray());
 check(Math.abs(before[0]-after[0])>.1,'drag orbits the heart');
 const distance=await page.evaluate(()=>window.__heartLab.controls.getDistance());
 await page.mouse.wheel(0,-200);
 await page.waitForFunction(d=>window.__heartLab.controls.getDistance()<d,distance);
 results.push('mouse wheel zoom');
 await page.getByRole('button',{name:'重置视角',exact:true}).click();
 await page.getByRole('button',{name:'切换心跳声音',exact:true}).click();
 check(await page.evaluate(()=>window.__heartLab.state.sound),'heartbeat audio enables after gesture');
 await page.getByRole('button',{name:'切换心跳声音',exact:true}).click();
 const downloaded=page.waitForEvent('download');await page.getByRole('button',{name:'保存画面',exact:true}).click();const download=await downloaded;await download.saveAs('output/playwright/exported-scene.png');check(download.suggestedFilename().endsWith('.png'),'PNG export downloads');
 await page.getByRole('button',{name:'科学依据 ↗',exact:true}).click();
 check(await page.locator('#info-dialog a').count()===3,'science references available');await page.keyboard.press('Escape');
 await page.waitForFunction(()=>!document.getElementById('toast').classList.contains('visible'));
 await page.screenshot({path:'output/playwright/desktop-final.png'});
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'output/playwright/mobile-final.png',fullPage:true});
 check(await page.evaluate(()=>document.documentElement.scrollWidth<=390),'mobile has no horizontal overflow');
 await page.getByRole('tab',{name:'烟草侵入'}).click();check(await page.getByRole('tab',{name:'烟草侵入'}).getAttribute('aria-selected')==='true','mobile mode switch');
 await page.setViewportSize({width:1440,height:960});await page.getByRole('tab',{name:'鲜活之心'}).click();
 return {passed:results,render:await page.evaluate(()=>({ms:window.__heartLab.lastRenderMs,frameSeconds:window.__heartLab.frameTime,geometries:window.__heartLab.renderer.info.memory.geometries}))};
}
